"""Integration matrix generator (B8).

Reflects the actual healthcheck() truth for each registered adapter.
Never overclaims adapter availability.

Design decisions:
- DECISION: build_matrix() is synchronous. It calls shutil.which() directly (same
  as the healthcheck implementations) to avoid requiring an event loop at import time.
  This keeps the matrix generator simple and testable without asyncio.
- DECISION: If an adapter's binary is not found, status='unavailable'. The matrix
  MUST NOT claim 'healthy' for an adapter whose binary is missing.
"""

import shutil

# ---------------------------------------------------------------------------
# Registry of known adapters and their binary names
# ---------------------------------------------------------------------------

ADAPTER_REGISTRY: list[dict] = [
    {
        "name": "nmap",
        "binary": "nmap",
        "description": "Network port scanner and service fingerprinter. "
        "Produces open-port observations and potential CVE findings via NSE scripts.",
        "adapter_class": "NmapAdapter",
        "profiles": ["discovery", "service", "scripts"],
    },
    {
        "name": "nikto",
        "binary": "nikto",
        "description": "Web server vulnerability scanner. "
        "Produces suspected-confidence findings. Alone, never yields confirmed status.",
        "adapter_class": "NiktoAdapter",
        "profiles": ["web"],
    },
]


def build_matrix() -> list[dict]:
    """Build an integration matrix reflecting real healthcheck truth.

    Returns a list of dicts with keys: name, status, description, binary_path.

    Invariant: An adapter may only have status='healthy' if its binary
    was actually found on PATH via shutil.which().
    """
    matrix: list[dict] = []
    for entry in ADAPTER_REGISTRY:
        binary_path = shutil.which(entry["binary"])
        status = "healthy" if binary_path else "unavailable"
        matrix.append(
            {
                "name": entry["name"],
                "binary": entry["binary"],
                "binary_path": binary_path or "not found",
                "status": status,
                "description": entry["description"],
                "adapter_class": entry["adapter_class"],
                "profiles": entry["profiles"],
            }
        )
    return matrix


def render_markdown(matrix: list[dict]) -> str:
    """Render the integration matrix as a Markdown table.

    Output is written to docs/INTEGRATION_MATRIX.md by the CLI or CI gate.
    """
    lines: list[str] = [
        "# Integration Matrix",
        "",
        "> Auto-generated by `cipher_lens.adapters.matrix`. "
        "Reflects actual binary availability at generation time.",
        "",
        "| Adapter | Binary | Status | Profiles | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in matrix:
        status_badge = "✅ healthy" if entry["status"] == "healthy" else "❌ unavailable"
        profiles = ", ".join(entry.get("profiles", []))
        desc = entry["description"].replace("|", "\\|")
        lines.append(
            f"| `{entry['name']}` | `{entry['binary']}` | {status_badge} "
            f"| {profiles} | {desc} |"
        )
    lines.append("")
    lines.append(
        f"_Generated at runtime. `{sum(1 for e in matrix if e['status'] == 'healthy')}`/"
        f"`{len(matrix)}` adapters healthy._"
    )
    return "\n".join(lines)


def main() -> None:
    """Print the generated markdown matrix to standard output."""
    import sys

    # Avoid encoding errors on Windows terminal with UTF-8 stream output
    output = render_markdown(build_matrix())
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()

